create table if not exists public.merl_level2_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  module_id text not null check (module_id in ('06','07','08','09','10')),
  lesson_evidence jsonb not null default '{}'::jsonb,
  quiz_score numeric(5,2),
  quiz_passed boolean not null default false,
  quiz_attempts integer not null default 0 check (quiz_attempts between 0 and 2),
  module_completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id,module_id)
);
create table if not exists public.merl_level2_evidence (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  module_id text not null check (module_id in ('06','07','08','09','10')),
  evidence_type text not null,
  content text not null check (char_length(content) between 20 and 20000),
  status text not null default 'submitted' check (status in ('submitted','accepted','revision_required')),
  submitted_at timestamptz not null default now(),
  unique(user_id,module_id)
);
create table if not exists public.merl_level2_quiz_items (
  module_id text not null check (module_id in ('06','07','08','09','10')),
  question_id text not null,
  question_order integer not null,
  stem text not null,
  options jsonb not null check (jsonb_typeof(options)='array'),
  correct_option integer not null check (correct_option>=0),
  active boolean not null default true,
  primary key(module_id,question_id)
);
create table if not exists public.merl_level2_quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  module_id text not null check (module_id in ('06','07','08','09','10')),
  answers jsonb not null,
  score numeric(5,2) not null,
  passed boolean not null,
  attempted_at timestamptz not null default now()
);
create index if not exists merl_level2_evidence_user_idx on public.merl_level2_evidence(user_id);
create index if not exists merl_level2_attempts_user_module_idx on public.merl_level2_quiz_attempts(user_id,module_id);

alter table public.merl_level2_progress enable row level security;
alter table public.merl_level2_evidence enable row level security;
alter table public.merl_level2_quiz_items enable row level security;
alter table public.merl_level2_quiz_attempts enable row level security;
revoke all on public.merl_level2_progress,public.merl_level2_evidence,public.merl_level2_quiz_items,public.merl_level2_quiz_attempts from public,anon,authenticated;
