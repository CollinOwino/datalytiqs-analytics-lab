create policy "Learners read own Level 2 attempts" on public.merl_level2_quiz_attempts for select to authenticated using ((select auth.uid())=user_id);

create or replace function public.merl_level2_previous_complete(p_user uuid,p_module text)
returns boolean language sql stable security definer set search_path='' as $$
 select case p_module
  when '06' then (select count(*)=5 from public.merl_level1_progress where user_id=p_user and module_completed_at is not null)
  when '07' then exists(select 1 from public.merl_level2_progress where user_id=p_user and module_id='06' and module_completed_at is not null)
  when '08' then exists(select 1 from public.merl_level2_progress where user_id=p_user and module_id='07' and module_completed_at is not null)
  when '09' then exists(select 1 from public.merl_level2_progress where user_id=p_user and module_id='08' and module_completed_at is not null)
  when '10' then exists(select 1 from public.merl_level2_progress where user_id=p_user and module_id='09' and module_completed_at is not null)
  else false end
$$;

create or replace function public.get_merl_level2_progress()
returns table(module_id text,lesson_evidence jsonb,evidence_submission jsonb,quiz_score numeric,quiz_passed boolean,quiz_attempts integer,module_completed_at timestamptz)
language sql stable security definer set search_path='' as $$
 with modules(module_id) as (values ('06'),('07'),('08'),('09'),('10'))
 select m.module_id,coalesce(p.lesson_evidence,'{}'::jsonb),
  (select jsonb_build_object('id',e.id,'evidence_type',e.evidence_type,'content',e.content,'status',e.status,'submitted_at',e.submitted_at)
   from public.merl_level2_evidence e where e.user_id=auth.uid() and e.module_id=m.module_id),
  p.quiz_score,coalesce(p.quiz_passed,false),coalesce(p.quiz_attempts,0),p.module_completed_at
 from modules m left join public.merl_level2_progress p on p.user_id=auth.uid() and p.module_id=m.module_id order by m.module_id
$$;

create or replace function public.mark_merl_level2_lesson(p_module_id text,p_lesson_index integer)
returns void language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_key text;
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 if p_module_id not in ('06','07','08','09','10') or p_lesson_index not between 0 and 2 then raise exception 'Invalid lesson'; end if;
 if not public.merl_level2_previous_complete(v_user,p_module_id) then raise exception 'Previous module must be completed first'; end if;
 v_key:=p_module_id||'-'||p_lesson_index;
 insert into public.merl_level2_progress(user_id,module_id,lesson_evidence,updated_at)
 values(v_user,p_module_id,jsonb_build_object(v_key,true),now())
 on conflict(user_id,module_id) do update set lesson_evidence=public.merl_level2_progress.lesson_evidence||excluded.lesson_evidence,updated_at=now();
end $$;

create or replace function public.submit_merl_level2_evidence(p_module_id text,p_evidence_type text,p_content text)
returns bigint language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid(); v_id bigint;
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 if p_module_id not in ('06','07','08','09','10') then raise exception 'Invalid module'; end if;
 if not public.merl_level2_previous_complete(v_user,p_module_id) then raise exception 'Previous module must be completed first'; end if;
 if char_length(trim(p_content))<20 or char_length(trim(p_content))>20000 then raise exception 'Evidence must contain 20 to 20000 characters'; end if;
 if (select count(*) from public.merl_level2_progress p,jsonb_each(p.lesson_evidence) item where p.user_id=v_user and p.module_id=p_module_id and item.value='true'::jsonb)<3 then raise exception 'Complete all lesson evidence first'; end if;
 insert into public.merl_level2_evidence(user_id,module_id,evidence_type,content) values(v_user,p_module_id,trim(p_evidence_type),trim(p_content)) returning id into v_id;
 return v_id;
end $$;

create or replace function public.get_merl_level2_quiz(p_module_id text)
returns table(question_id text,question_order integer,stem text,options jsonb)
language plpgsql stable security definer set search_path='' as $$
declare v_user uuid:=auth.uid();
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 if p_module_id not in ('06','07','08','09','10') then raise exception 'Invalid module'; end if;
 if not public.merl_level2_previous_complete(v_user,p_module_id) then raise exception 'Previous module must be completed first'; end if;
 if not exists(select 1 from public.merl_level2_evidence where user_id=v_user and module_id=p_module_id) then raise exception 'Professional evidence must be submitted before the quiz'; end if;
 return query select q.question_id,q.question_order,q.stem,q.options from public.merl_level2_quiz_items q where q.module_id=p_module_id and q.active order by q.question_order;
end $$;

create or replace function public.grade_merl_level2_quiz(p_module_id text,p_answers jsonb)
returns table(score numeric,passed boolean,attempts integer)
language plpgsql security definer set search_path='' as $$
declare v_user uuid:=auth.uid();v_score numeric(5,2);v_questions integer;v_answers integer;v_correct integer;v_attempts integer;v_passed boolean;v_now timestamptz:=now();
begin
 if v_user is null then raise exception 'Authentication required'; end if;
 if p_module_id not in ('06','07','08','09','10') then raise exception 'Invalid module'; end if;
 if not public.merl_level2_previous_complete(v_user,p_module_id) then raise exception 'Previous module must be completed first'; end if;
 perform 1 from public.merl_level2_progress where user_id=v_user and module_id=p_module_id for update;
 if (select count(*) from public.merl_level2_progress p,jsonb_each(p.lesson_evidence) item where p.user_id=v_user and p.module_id=p_module_id and item.value='true'::jsonb)<3 then raise exception 'Complete all lesson evidence first'; end if;
 if not exists(select 1 from public.merl_level2_evidence where user_id=v_user and module_id=p_module_id and status in ('submitted','accepted')) then raise exception 'Professional evidence must be submitted before the quiz'; end if;
 select count(*) into v_attempts from public.merl_level2_quiz_attempts where user_id=v_user and module_id=p_module_id;
 if v_attempts>=2 then raise exception 'Maximum quiz attempts reached'; end if;
 select count(*) into v_questions from public.merl_level2_quiz_items where module_id=p_module_id and active;
 select count(*) into v_answers from jsonb_object_keys(coalesce(p_answers,'{}'::jsonb));
 if v_questions=0 then raise exception 'Quiz is not configured'; end if;
 if v_answers<>v_questions then raise exception 'Every active quiz question must be answered exactly once'; end if;
 if exists(select 1 from jsonb_object_keys(p_answers) a where not exists(select 1 from public.merl_level2_quiz_items q where q.module_id=p_module_id and q.active and q.question_id=a)) then raise exception 'Answers contain an invalid question'; end if;
 select count(*) into v_correct from public.merl_level2_quiz_items q where q.module_id=p_module_id and q.active and p_answers?q.question_id and p_answers->>q.question_id=q.correct_option::text;
 v_score:=round((v_correct::numeric/v_questions)*100,2);v_passed:=v_score>=70;
 insert into public.merl_level2_quiz_attempts(user_id,module_id,answers,score,passed) values(v_user,p_module_id,p_answers,v_score,v_passed);
 update public.merl_level2_progress set quiz_score=greatest(coalesce(quiz_score,0),v_score),quiz_passed=quiz_passed or v_passed,quiz_attempts=v_attempts+1,module_completed_at=case when v_passed then coalesce(module_completed_at,v_now) else module_completed_at end,updated_at=v_now where user_id=v_user and module_id=p_module_id;
 return query select v_score::numeric,v_passed,v_attempts+1;
end $$;

